func TestGeneratedChainConfigForkRegistryCoversChainConfigForkFields(t *testing.T) {
	registered := make(map[string]struct{}, len(chainConfigForkBlockFields))
	for _, field := range chainConfigForkBlockFields {
		registered[field.name] = struct{}{}
	}

	typ := reflect.TypeOf(ChainConfig{})
	missing := make([]string, 0)
	for i := 0; i < typ.NumField(); i++ {
		field := typ.Field(i)
		if !field.IsExported() || field.Type != reflect.TypeOf((*big.Int)(nil)) {
			continue
		}
		if field.Name == "ChainID" {
			continue
		}
		if _, ok := registered[field.Name]; ok {
			continue
		}
		missing = append(missing, field.Name)
	}
	slices.Sort(missing)
	if len(missing) > 0 {
		t.Fatalf("expected unified fork registry to cover all top-level ChainConfig fork fields, missing %v", missing)
	}
}

