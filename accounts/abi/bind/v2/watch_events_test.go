// This file is the only carrier of the cases pinning the event signature
// sentinel errors. Upstream keeps them in accounts/abi/bind/v2/lib_test.go, a
// file this repository does not carry: TestEventUnpackEmptyTopics, and
// TestWatchEventsIgnoreMismatch, which upstream master already has but which
// only lands here with the ignore-mismatch change. A later port of that file
// must not bring the same-named functions along, as two tests with one name in
// package bind_test do not compile.

// TestEventUnpackEmptyTopics checks that the unpacker generated by abigen --v2
// reports a log that carries no topics, and a log whose first topic is not the
// event ID, with the exported sentinel errors rather than with an error created
// on the spot. The sentinels are exported so that generated code outside the
// package can return them, which is what lets a caller tell a log it did not ask
// for apart from a genuine decoding failure; the assertions below compare the
// errors by identity, which is stricter than an errors.Is match.
func TestEventUnpackEmptyTopics(t *testing.T) {
	c := events.NewC()

	for _, log := range []*types.Log{
		{Topics: []common.Hash{}},
		{Topics: nil},
	} {
		_, err := c.UnpackBasic1Event(log)
		if err == nil {
			t.Fatal("expected error when unpacking event with empty topics, got nil")
		}
		if err != bind.ErrNoEventSignature {
			t.Fatalf("expected 'no event signature' error, got: %v", err)
		}

		_, err = c.UnpackBasic2Event(log)
		if err == nil {
			t.Fatal("expected error when unpacking event with empty topics, got nil")
		}
		if err != bind.ErrNoEventSignature {
			t.Fatalf("expected 'no event signature' error, got: %v", err)
		}
	}
	// Non-empty topics that do not belong to the expected event.
	_, err := c.UnpackBasic1Event(&types.Log{Topics: []common.Hash{common.HexToHash("0x01")}})
	if err == nil {
		t.Fatal("expected error when unpacking event with foreign topics, got nil")
	}
	if err != bind.ErrEventSignatureMismatch {
		t.Fatalf("expected 'event signature mismatch' error, got: %v", err)
	}
}

// TestEventSignatureErrorsAreReExportedByV1Bind checks that accounts/abi/bind
// forwards the two sentinels as the very same values. Bindings generated
// without --v2 reference them through that package, and errors.Is matches on
// value identity, so an alias that merely repeats the message would not work.
func TestEventSignatureErrorsAreReExportedByV1Bind(t *testing.T) {
	if bindv1.ErrNoEventSignature != bind.ErrNoEventSignature {
		t.Fatalf("ErrNoEventSignature differs: %v (%p) in accounts/abi/bind, %v (%p) in accounts/abi/bind/v2",
			bindv1.ErrNoEventSignature, bindv1.ErrNoEventSignature, bind.ErrNoEventSignature, bind.ErrNoEventSignature)
	}
	if bindv1.ErrEventSignatureMismatch != bind.ErrEventSignatureMismatch {
		t.Fatalf("ErrEventSignatureMismatch differs: %v (%p) in accounts/abi/bind, %v (%p) in accounts/abi/bind/v2",
			bindv1.ErrEventSignatureMismatch, bindv1.ErrEventSignatureMismatch, bind.ErrEventSignatureMismatch, bind.ErrEventSignatureMismatch)
	}
}
